import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { letterGrade, ordinal } from './reportCardPdf';

const money = (value) =>
  `GHS ${Number(value || 0).toLocaleString(undefined, { minimumFractionDigits: 2, maximumFractionDigits: 2 })}`;

function safeName(value) {
  return (
    String(value || 'student')
      .replace(/[<>:"/\\|?*]/g, '')
      .replace(/\s+/g, ' ')
      .trim()
      .slice(0, 80) || 'student'
  );
}

function enrolledLabel(student) {
  if (!student?.enrolled_on) return student?.enrolled_year || '—';
  try {
    return new Date(student.enrolled_on).toLocaleDateString(undefined, { dateStyle: 'medium' });
  } catch {
    return student.enrolled_year || '—';
  }
}

export function downloadAlumniStudentPdf(student, schoolName = 'School') {
  const doc = new jsPDF({ unit: 'pt', format: 'a4' });
  const pageWidth = doc.internal.pageSize.getWidth();
  const terms = Array.isArray(student?.terms) ? student.terms : [];

  const header = (title) => {
    doc.setFontSize(16);
    doc.text(schoolName, pageWidth / 2, 40, { align: 'center' });
    doc.setFontSize(13);
    doc.text(title, pageWidth / 2, 60, { align: 'center' });
    doc.setFontSize(10);
    doc.setTextColor(80);
    doc.text(
      `${student.name || 'Student'}  ·  ${student.class || '—'}  ·  enrolled ${enrolledLabel(student)}`,
      pageWidth / 2,
      76,
      { align: 'center' }
    );
    doc.setTextColor(0);
  };

  header('Student record from enrollment');

  if (!terms.length) {
    doc.setFontSize(11);
    doc.text('No term records from the day of enrollment yet.', 40, 110);
    doc.save(`${safeName(student.name)}-enrollment-record.pdf`);
    return;
  }

  let first = true;
  for (const term of terms) {
    if (!first) doc.addPage();
    first = false;
    header(`${term.academic_year || 'Year'} · ${term.term || 'Term'}`);

    autoTable(doc, {
      startY: 92,
      head: [['Year', 'Term', 'Class', 'Days present', 'Late', 'Fees paid', 'Overall', 'Position']],
      body: [
        [
          term.academic_year || '—',
          term.term || '—',
          term.class_name || student.class || '—',
          String(term.attendance?.present_days || 0),
          String(term.attendance?.late_days || 0),
          money(term.fees?.paid_amount),
          term.overall_percent == null
            ? '—'
            : `${term.overall_percent}% · ${term.overall_grade || letterGrade(term.overall_percent)}`,
          ordinal(term.overall_position),
        ],
      ],
      styles: { fontSize: 9, cellPadding: 4 },
      headStyles: { fillColor: [14, 116, 144] },
      margin: { left: 40, right: 40 },
    });

    const afterSummary = doc.lastAutoTable?.finalY || 120;

    autoTable(doc, {
      startY: afterSummary + 16,
      head: [['Subject', 'Score', '%', 'Grade', 'Position', 'Attitude', 'Remark']],
      body: (term.subjects || []).length
        ? term.subjects.map((row) => [
            row.subject || '—',
            row.score == null ? '—' : `${row.score}/${row.max_score ?? 100}`,
            row.percent == null ? '—' : `${row.percent}%`,
            row.grade || letterGrade(row.percent),
            ordinal(row.position),
            row.attitude || '—',
            row.remark || '—',
          ])
        : [['No subjects recorded for this term', '', '', '', '', '', '']],
      styles: { fontSize: 9, cellPadding: 4 },
      headStyles: { fillColor: [52, 152, 219] },
      margin: { left: 40, right: 40 },
    });

    const afterSubjects = doc.lastAutoTable?.finalY || afterSummary;
    autoTable(doc, {
      startY: afterSubjects + 16,
      head: [['Fee date / month', 'Amount', 'Channel']],
      body: (term.fees?.payments || []).length
        ? term.fees.payments.map((row) => [
            row.month || (row.created_at ? String(row.created_at).slice(0, 10) : '—'),
            money(row.amount),
            row.channel || '—',
          ])
        : [['No fee payment this term', '', '']],
      styles: { fontSize: 9, cellPadding: 4 },
      headStyles: { fillColor: [16, 185, 129] },
      margin: { left: 40, right: 40 },
    });

    doc.setFontSize(8);
    doc.setTextColor(120);
    doc.text(
      'Each table is one term from the day of enrollment. Generated by SCHOOLTYPE.',
      pageWidth / 2,
      doc.internal.pageSize.getHeight() - 28,
      { align: 'center' }
    );
    doc.setTextColor(0);
  }

  doc.save(`${safeName(student.name)}-enrollment-record.pdf`);
}
